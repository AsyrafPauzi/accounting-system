export default function RowActionsMenu({ items = [], label = 'Actions' }) {
    const visible = items.filter((item) => item && item.show !== false);
    if (visible.length === 0) return null;

    return (
        <Menu as="div" className="relative inline-block text-left">
            <MenuButton
                className="inline-flex items-center justify-center w-9 h-9 rounded-xl border border-border-warm bg-surface text-ink hover:bg-cream hover:border-border-warm transition-colors"
                aria-label={label}
            >
                <ActionIcons.Ellipsis />
            </MenuButton>
            <MenuItems
                anchor="bottom end"
                transition
                className="z-[100] mt-2 w-52 origin-top-right rounded-xl bg-surface shadow-xl ring-1 ring-black/5 focus:outline-none py-1 transition duration-100 ease-out data-[closed]:scale-95 data-[closed]:opacity-0"
            >
                {visible.map((item) => {
                    const className = `${item.danger ? dangerClass : itemClass} ${item.disabled ? 'opacity-50 pointer-events-none' : ''}`;
                    const content = (
                        <>
                            {item.icon}
                            {item.label}
                        </>
                    );
                    const key = item.key || item.label;

                    return (
                        <MenuItem key={key} disabled={item.disabled}>
                            {item.href ? (
                                item.external ? (
                                    <a href={item.href} target="_blank" rel="noreferrer" className={className}>{content}</a>
                                ) : (
                                    <Link href={item.href} className={className}>{content}</Link>
                                )
                            ) : (
                                <button type="button" onClick={item.onClick} disabled={item.disabled} className={className}>
                                    {content}
                                </button>
                            )}
                        </MenuItem>
                    );
                })}
            </MenuItems>
        </Menu>
    );
}
